import assert from "node:assert/strict";
import { chromium } from "playwright";
const origin = process.env.DASH_TEST_ORIGIN ?? "http://localhost:3101";
const username = process.env.DASH_TEST_USERNAME;
const password = process.env.DASH_TEST_PASSWORD;
if (!username || !password) throw new Error("Set DASH_TEST_USERNAME and DASH_TEST_PASSWORD for an isolated test account");
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const calls = [];
const errors = [];
page.on("request", req => { const path = new URL(req.url()).pathname; if (path.startsWith("/api/")) calls.push(path); });
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(`${origin}/dash?model=cpar`);
  await page.waitForURL("**/login**");
  await page.getByRole("textbox", { name: "Username" }).fill(username);
  await page.getByRole("textbox", { name: "Password" }).fill(password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.waitForURL(url => !url.pathname.startsWith("/login"));
  calls.length = 0;
  await page.goto(`${origin}/dash?model=cuse`);
  await page.getByTestId("dash-thesis-panel").waitFor();
  assert(!calls.includes("/api/cpar/risk"), "cUSE DASH fetched inactive cPAR model");
  assert(!calls.some(path => path.startsWith("/api/portfolio/thes")), "Disabled thesis provider made requests");
  const tabs = await page.locator(".dash-tabs-center a").allTextContents();
  assert.deepEqual(tabs.slice(0, 2).map(x => x.trim()), ["DASH", "Risk"]);
  const count = await page.locator("[data-testid=dash-thesis-panel] tbody tr").count();
  assert(count > 0);
  assert.equal(await page.locator(".thesis-cell-trigger").count(), 0);
  await page.getByRole("button", { name: "Menu", exact: true }).click();
  assert.equal(await page.locator(".dash-dropdown").getByRole("link", { name: "DASH", exact: true }).count(), 0);
  await page.getByRole("button", { name: "Menu", exact: true }).click();
  const ticker = page.getByRole("columnheader", { name: /^Ticker/ });
  await ticker.focus();
  const before = await ticker.getAttribute("aria-sort");
  await page.keyboard.press("Enter");
  assert.notEqual(await ticker.getAttribute("aria-sort"), before);
  calls.length = 0;
  await page.route("**/api/cpar/risk", async route => { await new Promise(resolve => setTimeout(resolve, 600)); await route.continue(); });
  await page.getByRole("button", { name: "cPAR", exact: true }).click();
  await page.waitForURL("**/dash?model=cpar");
  await page.getByTestId("dash-thesis-panel").waitFor();
  assert(calls.includes("/api/cpar/risk"));
  assert(!calls.includes("/api/cuse/risk-page"), "cPAR DASH fetched inactive cUSE model");
  assert.equal(await page.locator("[data-testid=dash-thesis-panel] tbody tr").count(), count);
  assert.equal(await page.locator(".dash-tabs-center a").nth(1).getAttribute("href"), "/cpar/risk");
  await page.reload();
  await page.getByTestId("dash-thesis-panel").waitFor();
  assert.equal(await page.getByRole("button", { name: "cPAR", exact: true }).getAttribute("aria-pressed"), "true");
  await page.goBack();
  await page.getByTestId("dash-thesis-panel").waitFor();
  assert.equal(await page.getByRole("button", { name: "cUSE", exact: true }).getAttribute("aria-pressed"), "true");
  await page.goForward();
  await page.getByTestId("dash-thesis-panel").waitFor();
  assert.equal(await page.getByRole("button", { name: "cPAR", exact: true }).getAttribute("aria-pressed"), "true");
  await page.screenshot({ path: "/tmp/ceiora-port-dash-cpar.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/tmp/ceiora-port-dash-narrow.png" });
  const [brandRect, tabsRect, actionsRect] = await Promise.all([".dash-tabs-brand-cluster", ".dash-tabs-center", ".dash-tabs-actions"].map(selector => page.locator(selector).boundingBox()));
  assert(brandRect.x + brandRect.width <= tabsRect.x && tabsRect.x + tabsRect.width <= actionsRect.x, "Mobile navigation overlaps the brand or menu");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "DASH overflows narrow viewport");
  await page.unroute("**/api/cpar/risk");
  await page.route("**/api/cpar/risk", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Model temporarily unavailable" }) }));
  await page.reload();
  await page.getByRole("alert").waitFor();
  assert.equal(await page.getByTestId("dash-thesis-panel").count(), 0, "Old model data remained on failure");
  await page.getByRole("button", { name: "cUSE", exact: true }).click();
  await page.getByTestId("dash-thesis-panel").waitFor();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: "/tmp/ceiora-port-dash-cuse.png" });
  await page.unroute("**/api/cpar/risk");
  for (const path of ["/positions", "/cuse/exposures", "/cpar/risk"]) {
    console.log(`Checking feature-off ${path}`);
    await page.goto(`${origin}${path}`);
    await page.locator("tbody tr").first().waitFor();
    assert.equal(await page.getByRole("button", { name: "By thesis", exact: true }).count(), 0);
    assert.equal(await page.locator(".thesis-cell-trigger").count(), 0);
  }
  assert.deepEqual(errors, []);
  console.log("DASH auth, model isolation, URL persistence, holdings identity, menu/nav, keyboard, responsive layout, failure recovery, and feature-off table checks passed");
} finally { await browser.close(); }
